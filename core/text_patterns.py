"""テキスト処理で共有する文字クラス・正規表現

以前は chapter_detector / markdown_writer / text_cleanup / text_stats が
同義のパターンを別々に定義しており、微妙な差異 (対象文字の抜け) が
変更漏れの温床になっていた。実害のあるものをここに集約する。

意図的に統合していないもの:
- text_reflow._SHORT_LINE_THRESHOLD (=15) と
  chapter_detector._SHORT_LINE_THRESHOLD (=20) は同名だが別チューニング
  (段落結合の打ち切りと見出し候補の判定で最適値が違う)
"""

import re

# CJK (日本語) の基本文字クラス: ひらがな・カタカナ・CJK拡張A・CJK統合漢字。
# 文字クラス [ ] の中に埋め込んで使う
CJK_BASE = r"぀-ヿ㐀-䶿一-鿿"

# 単独行のページ番号・章番号 (「11」「- 12 -」「– 13 –」等)。
# 本文には不要なノイズ行の除去、および章検出でのページ番号行スキップに使う
STANDALONE_PAGE_NUM_RE = re.compile(r"^[\-‐ー–—:：\s]*\d{1,4}[\-‐ー–—:：\s]*$")

# 行頭の装飾記号 (シーン区切りの▲■◆等)。OCR が拾うと章タイトルの前に付き、
# それ自体を章と誤検出したり、後続の実タイトル (例「▲ エピローグ」) を汚す
DECOR_LEAD_RE = re.compile(r"^[▲△▼▽■□◆◇●○◎★☆※♦♢〓＊\s　]+")

# 見出しと本文の重複判定で無視する行頭の装飾・記号。
# DECOR_LEAD_RE と似ているが、比較用にダッシュ・コロン類も無視する別物
LEAD_JUNK_RE = re.compile(r"^[▲△▼▽■□◆◇●○◎★☆※♦♢〓＊\-‐ー–—:：\s　]+")
